use tabdat_stats::{EstimationSample, InstrumentalVariablesProblem, fit_cluster_two_step_gmm};

fn fixture() -> InstrumentalVariablesProblem {
  let rows: Vec<Vec<f64>> = include_str!("fixtures/cluster_gmm_many/data.csv")
    .lines()
    .skip(1)
    .map(|line| line.split(',').map(|cell| cell.parse().unwrap()).collect())
    .collect();
  let n = rows.len();
  let groups = rows.iter().map(|row| format!("{}", row[0])).collect();
  InstrumentalVariablesProblem {
    outcome: "y".into(),
    exogenous_names: vec![],
    endogenous_names: vec!["x1".into(), "x2".into()],
    instrument_names: (1..=20).map(|i| format!("z{i}")).collect(),
    response: rows.iter().map(|row| row[1]).collect(),
    exogenous: vec![vec![]; n],
    endogenous: rows.iter().map(|row| row[2..4].to_vec()).collect(),
    instruments: rows.iter().map(|row| row[4..].to_vec()).collect(),
    include_intercept: false,
    sample: Some(EstimationSample::new((0..n).collect(), n, 0, None, Some(groups)).unwrap()),
  }
}

fn near(actual: f64, expected: f64) {
  assert!(
    (actual - expected).abs() <= 1e-10 + 1e-10 * expected.abs(),
    "actual={actual:.17e} expected={expected:.17e}"
  );
}

#[test]
fn twenty_instruments_match_independent_r_and_rescaling() {
  // Generated by stacked_gmm_synthetic_reference.R with R 4.6.1.
  let expected: Vec<f64> = include_str!("fixtures/cluster_gmm_many/reference.csv")
    .lines()
    .nth(1)
    .unwrap()
    .split(',')
    .map(|value| value.parse().unwrap())
    .collect();
  let mut problem = fixture();
  let fit = fit_cluster_two_step_gmm(&problem).unwrap();
  assert_eq!(fit.cluster_count, 64);
  for (i, expected) in expected[..2].iter().enumerate() {
    near(fit.coefficients[i], *expected);
  }
  for (cov, offset) in [(&fit.fixed_covariance, 2), (&fit.updated_covariance, 5)] {
    near(cov[0][0], expected[offset]);
    near(cov[0][1], expected[offset + 1]);
    near(cov[1][1], expected[offset + 2]);
  }
  near(fit.fixed_j.unwrap(), expected[8]);
  near(fit.updated_j.unwrap(), expected[9]);
  near(fit.fixed_j_p_value.unwrap(), expected[10]);
  near(fit.updated_j_p_value.unwrap(), expected[11]);
  for row in &mut problem.instruments {
    for (i, value) in row.iter_mut().enumerate() {
      *value *= if i % 2 == 0 { 1e4 } else { 1e-4 };
    }
  }
  let scaled = fit_cluster_two_step_gmm(&problem).unwrap();
  for i in 0..2 {
    near(scaled.coefficients[i], fit.coefficients[i]);
    for j in 0..2 {
      near(scaled.fixed_covariance[i][j], fit.fixed_covariance[i][j]);
      near(
        scaled.updated_covariance[i][j],
        fit.updated_covariance[i][j],
      );
    }
  }
  near(scaled.fixed_j.unwrap(), fit.fixed_j.unwrap());
  near(scaled.updated_j.unwrap(), fit.updated_j.unwrap());
}

#[test]
fn rejects_many_instrument_rank_cluster_and_size_failures() {
  let mut problem = fixture();
  for row in &mut problem.instruments {
    row[19] = row[0];
  }
  assert!(fit_cluster_two_step_gmm(&problem).is_err());
  problem = fixture();
  problem.sample.as_mut().unwrap().cluster_groups = Some(
    (0..problem.response.len())
      .map(|i| format!("{}", i % 20))
      .collect(),
  );
  let error = fit_cluster_two_step_gmm(&problem).unwrap_err().to_string();
  assert!(error.contains("more clusters than instruments"), "{error}");
  problem = fixture();
  for i in 20..73 {
    problem.instrument_names.push(format!("z{}", i + 1));
  }
  for row in &mut problem.instruments {
    row.resize(73, 1.0);
  }
  let error = fit_cluster_two_step_gmm(&problem).unwrap_err().to_string();
  assert!(error.contains("72 instruments"), "{error}");
}
