use tabdat_stats::{EstimationProblem, EstimationSample, classical_panel_hausman};

fn problem(data: &str, synthetic: bool) -> EstimationProblem {
  let rows: Vec<Vec<&str>> = data
    .lines()
    .skip(1)
    .map(|line| line.split(',').collect())
    .collect();
  let mut y = Vec::new();
  let mut x = Vec::new();
  let mut groups = Vec::new();
  for row in rows {
    let (id, outcome, predictor) = if synthetic {
      (row[0], row[2], row[3])
    } else {
      (row[7], row[1], row[2])
    };
    if let (Ok(outcome), Ok(predictor)) = (outcome.parse(), predictor.parse()) {
      y.push(outcome);
      x.push(vec![predictor]);
      groups.push(id.to_owned());
    }
  }
  let n = y.len();
  let sample = EstimationSample::new((0..n).collect(), n, 0, None, Some(groups)).unwrap();
  EstimationProblem::new("y", vec!["x".into()], y, x)
    .unwrap()
    .with_sample(sample)
}

#[test]
fn balanced_scalar_comparison_matches_independent_plm() {
  // Generated by examples/mma21p1panel/classical_hausman_synthetic_reference.R.
  let p = problem(
    include_str!("fixtures/panel_classical_hausman/data.csv"),
    true,
  );
  let result = classical_panel_hausman(&p, "id").unwrap();
  let json = serde_json::to_value(&result).unwrap();
  let mut count = 0;
  for line in include_str!("fixtures/panel_classical_hausman/reference.csv")
    .lines()
    .skip(1)
  {
    let (field, expected) = line.split_once(',').unwrap();
    let expected: f64 = expected.parse().unwrap();
    let actual = json[field].as_f64().unwrap();
    assert!(
      (actual - expected).abs() <= 1e-10 + 1e-10 * expected.abs(),
      "{field}: {actual} != {expected}"
    );
    count += 1;
  }
  assert_eq!(count, 12);
}

#[test]
fn rejects_indefinite_covariance_and_unsupported_designs() {
  // plm's unconstrained phtest prints a positive statistic even for this negative
  // variance difference; do not silently take its absolute value.
  let p = problem(include_str!("fixtures/panel_hausman/inputs.csv"), false);
  let error = classical_panel_hausman(&p, "id").unwrap_err().to_string();
  assert!(error.contains("nonpositive"), "{error}");
  let mut p = problem(
    include_str!("fixtures/panel_classical_hausman/data.csv"),
    true,
  );
  p.predictor_names.push("x2".into());
  for row in &mut p.design_matrix {
    row.push(row[0]);
  }
  assert!(classical_panel_hausman(&p, "id").is_err());
  let mut p = problem(
    include_str!("fixtures/panel_classical_hausman/data.csv"),
    true,
  );
  p.include_intercept = false;
  assert!(classical_panel_hausman(&p, "id").is_err());
  let mut p = problem(
    include_str!("fixtures/panel_classical_hausman/data.csv"),
    true,
  );
  p.response.pop();
  p.design_matrix.pop();
  let sample = p.sample.as_mut().unwrap();
  sample.retained_indices.pop();
  sample.total_observations -= 1;
  sample.cluster_groups.as_mut().unwrap().pop();
  assert!(classical_panel_hausman(&p, "id").is_err());
}
