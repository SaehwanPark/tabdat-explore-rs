use tabdat_stats::{EstimationSample, InstrumentalVariablesProblem, fit_cluster_two_step_gmm};

fn fixture(exact: bool) -> InstrumentalVariablesProblem {
  let rows: Vec<Vec<f64>> = include_str!("fixtures/cluster_gmm/data.csv")
    .lines()
    .skip(1)
    .map(|line| line.split(',').map(|cell| cell.parse().unwrap()).collect())
    .collect();
  let n = rows.len();
  let groups = rows.iter().map(|row| format!("{}", row[0])).collect();
  InstrumentalVariablesProblem {
    outcome: "y".into(),
    exogenous_names: vec![],
    endogenous_names: vec!["x".into()],
    instrument_names: if exact {
      vec!["z1".into()]
    } else {
      vec!["z1".into(), "z2".into()]
    },
    response: rows.iter().map(|row| row[1]).collect(),
    exogenous: vec![vec![]; n],
    endogenous: rows.iter().map(|row| vec![row[2]]).collect(),
    instruments: rows
      .iter()
      .map(|row| {
        if exact {
          vec![row[3]]
        } else {
          vec![row[3], row[4]]
        }
      })
      .collect(),
    include_intercept: false,
    sample: Some(EstimationSample::new((0..n).collect(), n, 0, None, Some(groups)).unwrap()),
  }
}

fn reference(exact: bool) -> Vec<f64> {
  let csv = if exact {
    include_str!("fixtures/cluster_gmm/exact.csv")
  } else {
    include_str!("fixtures/cluster_gmm/overidentified.csv")
  };
  csv
    .lines()
    .nth(1)
    .unwrap()
    .split(',')
    .map(|value| value.parse().unwrap())
    .collect()
}

fn near(actual: f64, expected: f64) {
  assert!(
    (actual - expected).abs() <= 1e-11 + 1e-11 * expected.abs(),
    "actual={actual:.17e} expected={expected:.17e}"
  );
}

#[test]
fn overidentified_two_step_matches_independent_r() {
  // Generated by examples/mma22p1panel/gmm_synthetic_reference.R with R 4.6.1.
  let problem = fixture(false);
  let result = fit_cluster_two_step_gmm(&problem).unwrap();
  assert_eq!(result.cluster_count, 16);
  let expected = reference(false);
  near(result.coefficients[0], expected[0]);
  near(result.fixed_covariance[0][0], expected[1]);
  near(result.updated_covariance[0][0], expected[2]);
  near(result.fixed_j.unwrap(), expected[3]);
  near(result.updated_j.unwrap(), expected[4]);
  near(result.fixed_j_p_value.unwrap(), 0.42168672894697545);
  near(result.updated_j_p_value.unwrap(), 0.42226891458331434);
  for (i, row) in problem.endogenous.iter().enumerate() {
    near(result.fitted_values[i], row[0] * result.coefficients[0]);
    near(
      result.residuals[i],
      problem.response[i] - result.fitted_values[i],
    );
  }
}

#[test]
fn exactly_identified_has_no_overidentification_test() {
  let result = fit_cluster_two_step_gmm(&fixture(true)).unwrap();
  let expected = reference(true);
  near(result.coefficients[0], expected[0]);
  near(result.fixed_covariance[0][0], expected[1]);
  near(result.updated_covariance[0][0], expected[2]);
  assert_eq!(result.fixed_j, None);
  assert_eq!(result.updated_j, None);
  assert_eq!(result.fixed_j_p_value, None);
  assert_eq!(result.updated_j_p_value, None);
}

#[test]
fn instrument_and_regressor_rescaling_preserves_gmm() {
  let mut problem = fixture(false);
  let original = fit_cluster_two_step_gmm(&problem).unwrap();
  for row in &mut problem.instruments {
    row[0] *= 1e6;
    row[1] *= 1e-5;
  }
  for row in &mut problem.endogenous {
    row[0] *= 1000.0;
  }
  let scaled = fit_cluster_two_step_gmm(&problem).unwrap();
  near(scaled.coefficients[0] * 1000.0, original.coefficients[0]);
  near(
    scaled.fixed_covariance[0][0] * 1e6,
    original.fixed_covariance[0][0],
  );
  near(
    scaled.updated_covariance[0][0] * 1e6,
    original.updated_covariance[0][0],
  );
  near(scaled.fixed_j.unwrap(), original.fixed_j.unwrap());
  near(scaled.updated_j.unwrap(), original.updated_j.unwrap());
}

#[test]
fn rejects_unsupported_and_singular_designs() {
  let mut problem = fixture(false);
  problem.include_intercept = true;
  assert!(fit_cluster_two_step_gmm(&problem).is_err());
  problem = fixture(false);
  problem.sample.as_mut().unwrap().cluster_groups =
    Some(vec!["same".into(); problem.response.len()]);
  assert!(fit_cluster_two_step_gmm(&problem).is_err());
  problem = fixture(false);
  for row in &mut problem.instruments {
    row[1] = row[0];
  }
  assert!(fit_cluster_two_step_gmm(&problem).is_err());
  problem = fixture(false);
  for i in 3..problem.response.len() {
    let j = i % 3;
    problem.response[i] = problem.response[j];
    problem.endogenous[i] = problem.endogenous[j].clone();
    problem.instruments[i] = problem.instruments[j].clone();
  }
  let error = fit_cluster_two_step_gmm(&problem).unwrap_err().to_string();
  assert!(error.contains("pilot cluster moment covariance"), "{error}");
  problem = fixture(false);
  problem.response = problem.endogenous.iter().map(|row| 2.0 * row[0]).collect();
  assert!(fit_cluster_two_step_gmm(&problem).is_err());
}
